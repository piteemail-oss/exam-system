export function getSoundEnabled() {
  try {
    const val = localStorage.getItem('sound_enabled')
    return val !== '0'
  } catch {
    return true
  }
}

export function setSoundEnabled(enabled) {
  localStorage.setItem('sound_enabled', enabled ? '1' : '0')
}
